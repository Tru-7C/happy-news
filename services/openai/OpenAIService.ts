import OpenAI from "openai";

const apiKey = process.env.OPENAI_API_KEY;

if (!apiKey) {
  throw new Error("OPENAI_API_KEY is not set");
}

const openai = new OpenAI({
  apiKey,
});

export type NewsAnalysis = {
  title: string;
  summary: string;
  happy_score: number;
  category:
    | "community"
    | "children"
    | "animals"
    | "environment"
    | "culture"
    | "sports"
    | "achievement"
    | "technology"
    | "other";
  reason: string;
};

export async function analyzeNews(
  title: string,
  description: string
): Promise<NewsAnalysis> {
  const response = await openai.responses.create({
    model: "gpt-5-mini",
    input: `
あなたは「Happy News」の編集者です。

Happy Newsは、読んだ人がふっと笑顔になったり、
心が温かくなったり、地元を懐かしく感じたりする温かいニュースを集めるサイトです。

単に明るいニュースや、地域で起きたニュースを集めるのではありません。
読者が「なんだかいいな」「こういう話、好きだな」
「地元っていいな」と感じられるニュースを優先してください。

以下のニュースを分析し、採用する価値があるかを厳しく評価してください。

元のタイトル:
${title}

説明:
${description}

次のJSON形式だけで返してください。

{
  "title": "",
  "summary": "",
  "happy_score": 0,
  "category": "",
  "reason": ""
}

【happy_score：最も重要なルール】

1〜100の整数で採点してください。

点数は、ニュースがどれほど明るいかではなく、
どれほど心温まる内容で、Happy Newsの読者に届けたいかを評価します。

90〜100点：
人の優しさ、心温まる交流、動物と人との触れ合い、
子どもたちの微笑ましい姿、地域の人々の温かな協力など、
読んだ人が自然に笑顔になれるニュース。
例えば、地元の幼稚園児が芋掘り体験に参加した、など。

80〜89点：
地域の人の地道な取り組み、心温まる地域行事、
地域に根付いた文化や風景、動物や自然との触れ合い、
誰かの努力が実を結んだ話など、
読者が親しみや温かさを感じられるニュース。
例えば、昔から地元で開催されているお祭りの様子など。

65〜79点：
明るい話題ではあるニュース。
新商品の紹介、施設の案内、イベントの開催など。
単なる大会結果や活動報告など。

1〜64点：
一般的なイベント告知、チャンネル登録のお願いなどß
政治、選挙、行政の一般的な動き、経済、
事件、事故、災害への注意喚起、犯罪、対立、
深刻な問題、芸能人のゴシップなど。


特に重要なルール：
- 地域のニュースだからという理由だけで高得点にしない
- 子ども、動物、自然が登場するだけで高得点にしない
- 明るい話題でも、心温まる要素がなければ80点未満にする
- 説明文に情報が少ない場合、想像で感動的な話に仕立てない

【title】

- 元のニュースの事実に忠実にする
- 例えば、「商業施設でバレエ公演が行われる」でなはく、「地元の子どもたちがバレエを披露」のように地元を懐かしむ人が読んでみたくなるタイトルにする
- 事実が許す範囲で、優しさ、温かさ、親しみが感じられる表現を使う
- 新聞のように硬すぎる表現や、事務的な表現を避ける
- 読者の興味を引くために、感動や喜びを勝手に作り出さない
- 地域名は省略する
- 30〜40文字程度を目安にする。ただし、不自然に長くしない
- 「公式動画」「動画で紹介」「配信中」「公開」「YouTube」などの表現を入れない
- 「紹介する」「紹介」「伝える」など、報道行為そのものを表す表現を入れない
- 「話題に」「注目集める」など、根拠のない反響を示す表現を使わない
- ニュースの出来事や人・動物の具体的な行動を主役にする

【summary】

- 100文字以内
- 元の説明にある事実を分かりやすく伝える
- 読者がその場の様子を思い浮かべられる自然な文章にする
- 事実に沿って、温かさや親しみが感じられる表現を選ぶ
- 事実にない感情、会話、出来事、反響を追加しない
- 「〜が紹介されました」「〜が伝えられました」の繰り返しを避ける
- 元の説明が短く、詳しい様子が分からない場合は、無理に感動的な文章にしない

【category】

次のいずれかを選んでください。
community
children
animals
environment
culture
sports
achievement
technology
other

ニュースの中心的な内容に最も合うカテゴリを選んでください。

【reason】

- その点数にした理由を簡潔に説明する
- 心温まる要素があるか、どの点が評価できるかを説明する
- 高得点にしなかった場合は、その理由も説明する

【最終確認】

回答する前に、タイトルと説明文が元のニュースの事実に忠実か、
そして本当にHappy Newsに掲載したい内容かを確認してください。

JSON以外の文章は返さないでください。
`,
  });

  const result = JSON.parse(response.output_text);

  return result;
}

export async function generateNewsIntro(
  title: string,
  description: string,
  summary: string
): Promise<string> {
  const response = await openai.responses.create({
    model: "gpt-5-mini",
    input: `
あなたは「Happy News」の編集者です。

ニュース動画を見る前に読む、短い導入文を書いてください。
TED Talks Dailyのホストが本編の前に背景や注目点を語るように、
読者がニュースの意味や注目ポイントを理解できる文章にします。

【目的】
- ニュースの背景や文脈を伝える
- どこに注目するとよいかを示す
- なぜ知る価値があるのかを伝える
- 読者が動画を見てみたくなる自然な文章にする

【元のニュースタイトル】
${title}

【動画の説明】
${description}

【ニュースの要約】
${summary}

【執筆ルール】
- 150〜250文字程度
- 自然で読みやすい日本語にする
- 背景、注目ポイント、知る価値が自然につながる構成にする
- 元の情報にない出来事、背景、人物の気持ち、社会的影響を作らない
- 情報が少ない場合は、無理に背景や「今見るべき理由」を作らない
- 大げさな感動表現や根拠のない称賛を避ける
- 最初に読者に問いかけるような表現を含めても良いので、その話題についてふと立ち止まって考えてしまうような文章にする。
- ニュースの要約を言い換えるだけで終わらせない
- 「このニュースを見てみましょう」などの定型文で締めくくらない
- 動画の内容を実際に確認できていない場合、話されている内容を断定しない

導入文だけを返してください。
`,
  });

  return response.output_text.trim();
}